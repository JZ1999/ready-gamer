# Ready Gamer — BGB headless e2e runner
# Builds one Debug ROM per scenario, runs bgb -hf, saves screenshot (+ optional AVI/GIF).
#
# Usage:
#   .\tools\e2e\run_e2e.ps1
#   .\tools\e2e\run_e2e.ps1 -Scenarios die,electric,coins
#   .\tools\e2e\run_e2e.ps1 -Capture
#
param(
    [string]$Scenarios = "die,room1_die,electric,coins",
    [switch]$Capture,
    [int]$TimeoutSec = 600
)

$ErrorActionPreference = "Stop"
$Root = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$Src = Join-Path $Root "src"
$ScenarioHeader = Join-Path $Root "include\E2E_scenario.h"
$ArtifactsRoot = Join-Path $Root "tools\e2e\artifacts"
$ConvertScript = Join-Path $PSScriptRoot "Convert-AviToFrames.ps1"
$Make = Join-Path $env:ZGB_PATH "..\env\make-3.81-bin\bin\make.exe"
$Bgb = Join-Path $env:ZGB_PATH "..\env\bgb\bgb.exe"
$Rom = Join-Path $Root "bin\READY_GAMER_Debug.gb"

if (-not $env:ZGB_PATH) {
    Write-Error "ZGB_PATH is not set (should point at ZGB/common)."
}
if (-not (Test-Path $Make)) { Write-Error "make not found: $Make" }
if (-not (Test-Path $Bgb)) { Write-Error "bgb not found: $Bgb" }

$ScenarioMap = [ordered]@{
    die         = @{ Id = 1; Expect = "Real GameOver from enemy damage"; Title = "Die in room 0"; ExpectGameOver = $true }
    room1_die   = @{ Id = 2; Expect = "Earn coins, buy door, portal, die IN room1 (death in room0 = fail)"; Title = "Clear room 0, die in room 1"; ExpectGameOver = $true }
    full_clear  = @{ Id = 3; Expect = "Whole game from room 0: farm coins, every power-up, all rooms, boss run + fight to Win"; Title = "Full game to win"; ExpectGameOver = $false }
    electric    = @{ Id = 4; Expect = "Earn 2 doors + portal, grab the real room1 electricity pickup"; Title = "Electricity power-up"; ExpectGameOver = $false }
    coins       = @{ Id = 5; Expect = "Earn coins by killing enemies"; Title = "Coins from kills"; ExpectGameOver = $false }
}

function Write-ScenarioHeader([int]$id) {
    $text = @"
/* Auto-generated by tools/e2e/run_e2e.ps1 - do not edit by hand while e2e is running. */
#ifndef E2E_SCENARIO
#define E2E_SCENARIO $id
#endif
"@
    Set-Content -Path $ScenarioHeader -Value $text -Encoding ascii
}

function Build-E2ERom {
    Push-Location $Src
    try {
        & $Make build_gb BUILD_TYPE=Debug
        if ($LASTEXITCODE -ne 0) { throw "make failed with exit $LASTEXITCODE" }
    } finally {
        Pop-Location
    }
    if (-not (Test-Path $Rom)) { throw "ROM missing after build: $Rom" }
}

# The ROM paints its verdict into the last frame before EMU_BREAKPOINT:
# every pixel lightest = PASS, every pixel darkest = FAIL (see src/systems/E2E.c).
# Anything else (gameplay frame, partial) = no verdict = FAIL.
function Get-RomVerdict([string]$pngPath) {
    if (-not (Test-Path $pngPath)) { return "none" }
    if ((Get-Item $pngPath).Length -le 0) { return "none" }
    Add-Type -AssemblyName System.Drawing -ErrorAction SilentlyContinue
    $bmp = [System.Drawing.Bitmap]::FromFile((Resolve-Path $pngPath))
    try {
        $light = 0; $dark = 0; $n = 0
        for ($y = 4; $y -lt $bmp.Height; $y += 12) {
            for ($x = 4; $x -lt $bmp.Width; $x += 12) {
                $c = $bmp.GetPixel($x, $y)
                $s = $c.R + $c.G + $c.B
                if ($s -ge 560) { $light++ } elseif ($s -le 150) { $dark++ }
                $n++
            }
        }
        if ($light -eq $n) { return "pass" }
        if ($dark -eq $n) { return "fail" }
        return "none"
    } finally {
        $bmp.Dispose()
    }
}

function Convert-Avi([string]$aviPath, [string]$framesDir) {
    if (-not (Test-Path $ConvertScript)) { return 0 }
    try {
        & $ConvertScript -AviPath $aviPath -OutDir $framesDir -MaxFrames 300
        $meta = Join-Path $framesDir "meta.json"
        if (-not (Test-Path $meta)) { return 0 }
        $obj = Get-Content $meta -Raw | ConvertFrom-Json
        return [int]$obj.count
    } catch {
        Write-Warning "Frame extract failed for ${aviPath}: $_"
        return 0
    }
}

function Invoke-BgbRun([string]$outDir, [string]$name) {
    if (Test-Path $outDir) { Remove-Item -Recurse -Force $outDir }
    New-Item -ItemType Directory -Force -Path $outDir | Out-Null
    $destShot = Join-Path $outDir "final.png"
    $framesDir = Join-Path $outDir "frames"

    # BGB mishandles paths with spaces ("ready gamer") — stage under %TEMP%.
    $stageDir = Join-Path $env:TEMP ("rge2e\" + $name)
    if (Test-Path $stageDir) { Remove-Item -Recurse -Force $stageDir }
    New-Item -ItemType Directory -Force -Path $stageDir | Out-Null

    $romAbs = Join-Path $stageDir "rom.gb"
    $shotAbs = Join-Path $stageDir "final.png"
    $aviAbs = Join-Path $stageDir $name
    Copy-Item -Force $Rom $romAbs

    $bgbArgs = @(
        "-rom", $romAbs,
        "-autoexit",
        "-nowarn",
        "-nowriteini",
        "-nobatt",
        "-setting", "Sound=0",
        "-screenonexit", $shotAbs,
        "-hf"
    )
    if ($Capture) {
        $bgbArgs += @(
            "-setting", "RecordAVI=1",
            "-setting", ("RecordPrefix=" + $aviAbs)
        )
    }

    $proc = Start-Process -FilePath $Bgb -ArgumentList $bgbArgs -PassThru -WindowStyle Hidden
    if (-not $proc.WaitForExit($TimeoutSec * 1000)) {
        Stop-Process -Id $proc.Id -Force -ErrorAction SilentlyContinue
        Get-Process -Name "bgb" -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
        Start-Sleep -Milliseconds 400
        Copy-Item -Force $romAbs (Join-Path $outDir "READY_GAMER_Debug.gb") -ErrorAction SilentlyContinue
        # Keep partial capture so timeouts are still reviewable.
        Get-ChildItem -Path $stageDir -Filter "*.avi" -ErrorAction SilentlyContinue | ForEach-Object {
            Copy-Item -Force $_.FullName (Join-Path $outDir $_.Name)
            Convert-Avi $_.FullName $framesDir | Out-Null
        }
        $fc = 0
        $meta = Join-Path $framesDir "meta.json"
        if (Test-Path $meta) { $fc = [int]((Get-Content $meta -Raw | ConvertFrom-Json).count) }
        return @{ Ok = $false; Reason = "timeout after ${TimeoutSec}s"; Shot = $destShot; FrameCount = $fc; Avis = @(Get-ChildItem $outDir -Filter "*.avi" -EA SilentlyContinue | ForEach-Object { $_.FullName }) }
    }

    Start-Sleep -Milliseconds 300
    $ok = ($proc.ExitCode -eq 0)

    if ($Capture -and $ok) {
        $shot2 = Join-Path $stageDir "final_shot.png"
        $pngArgs = @(
            "-rom", $romAbs,
            "-hf", "-autoexit", "-nowarn", "-nowriteini", "-nobatt",
            "-setting", "Sound=0",
            "-screenonexit", $shot2
        )
        $p2 = Start-Process -FilePath $Bgb -ArgumentList $pngArgs -PassThru -WindowStyle Hidden
        if ($p2.WaitForExit([Math]::Min($TimeoutSec, 90) * 1000)) {
            if ((Test-Path $shot2) -and ((Get-Item $shot2).Length -gt 0)) {
                Copy-Item -Force $shot2 $shotAbs
            }
        } else {
            Stop-Process -Id $p2.Id -Force -ErrorAction SilentlyContinue
        }
    }

    Copy-Item -Force $romAbs (Join-Path $outDir "READY_GAMER_Debug.gb") -ErrorAction SilentlyContinue
    if ((Test-Path $shotAbs) -and ((Get-Item $shotAbs).Length -gt 0)) {
        Copy-Item -Force $shotAbs $destShot
    }

    $avis = @()
    $frameCount = 0
    Get-ChildItem -Path $stageDir -Filter "*.avi" -ErrorAction SilentlyContinue | ForEach-Object {
        $destAvi = Join-Path $outDir $_.Name
        Copy-Item -Force $_.FullName $destAvi
        $avis += $destAvi
        $frameCount = Convert-Avi $_.FullName $framesDir
    }

    $hasShot = (Test-Path $destShot) -and ((Get-Item $destShot).Length -gt 0)
    $notes = @()
    if ($hasShot) { $notes += "screenshot" }
    if ($frameCount -gt 0) { $notes += "frames=$frameCount" }
    if ($avis.Count -gt 0) { $notes += "avi=$($avis.Count)" }
    $noteStr = if ($notes.Count) { ", " + ($notes -join ", ") } else { "" }
    $reason = if ($ok) { "pass (exit 0$noteStr)" } else { "fail (exit $($proc.ExitCode)$noteStr)" }
    return @{ Ok = $ok; Reason = $reason; Shot = $destShot; FrameCount = $frameCount; Avis = $avis }
}

function Write-ReportHtml([array]$rows) {
    $stamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    $cards = New-Object System.Collections.Generic.List[string]

    foreach ($r in $rows) {
        $media = ""
        if ($r.FrameCount -gt 0) {
            $media += "<div class=`"vid`" data-frames=`"$($r.Name)/frames`" data-count=`"$($r.FrameCount)`"><canvas width=`"160`" height=`"144`"></canvas><div class=`"controls`"><button type=`"button`" data-act=`"restart`">Replay</button></div></div>"
        }
        if (Test-Path $r.Shot) {
            $rel = $r.Shot.Substring($ArtifactsRoot.Length).TrimStart("\", "/").Replace("\", "/")
            $media += "<p class=`"cap`">Final frame</p><img class=`"shot`" src=`"$rel`" alt=`"$($r.Name)`" width=`"320`" />"
        } else {
            $media += "<em>no screenshot</em>"
        }

        $links = ""
        foreach ($a in $r.Avis) {
            $rel = $a.Substring($ArtifactsRoot.Length).TrimStart("\", "/").Replace("\", "/")
            $links += "<a href=`"$rel`">raw avi</a> "
        }

        $cls = if ($r.Ok) { "pass" } else { "fail" }
        $card = "<div class=`"card $cls`"><h2>$($r.Title)</h2><p><code>$($r.Name)</code> - $($r.Reason)</p><p>Expect: $($r.Expect)</p>$media<p class=`"links`">$links</p></div>"
        $cards.Add($card) | Out-Null
    }

    $mode = if ($Capture) { "in-browser frame playback + screenshots (+ raw AVI)" } else { "screenshots only (use -Capture for video)" }
    $body = $cards -join "`n"
    $html = @(
        "<!DOCTYPE html>",
        "<html lang=`"en`"><head><meta charset=`"utf-8`" />",
        "<title>Ready Gamer e2e report</title>",
        "<style>",
        "body{font-family:system-ui,sans-serif;background:#111;color:#eee;margin:1.5rem}",
        "h1{font-size:1.25rem}",
        ".grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(360px,1fr));gap:1rem}",
        ".card{border:1px solid #333;border-radius:8px;padding:1rem;background:#1a1a1a}",
        ".card.pass{border-color:#2a6}.card.fail{border-color:#c33}",
        "img,canvas{image-rendering:pixelated;background:#000;display:block;margin-top:.5rem}",
        ".vid canvas{width:320px;height:288px;border:1px solid #444}",
        ".controls{margin-top:.35rem}",
        ".controls button{background:#333;color:#eee;border:1px solid #555;padding:.25rem .6rem;cursor:pointer}",
        ".cap{margin:.75rem 0 0;font-size:.85rem;color:#aaa}",
        "a{color:#8cf}",
        "</style></head><body>",
        "<h1>Ready Gamer e2e - $stamp</h1>",
        "<p>Capture mode: $mode</p>",
        "<div class=`"grid`">",
        $body,
        "</div>",
        "<script>",
        "document.querySelectorAll('.vid[data-frames]').forEach(function(box){",
        "  var base=box.getAttribute('data-frames');",
        "  var count=parseInt(box.getAttribute('data-count'),10)||0;",
        "  var canvas=box.querySelector('canvas');",
        "  var ctx=canvas.getContext('2d');",
        "  var i=0, timer=null, images=[];",
        "  function pad(n){return ('000'+n).slice(-4);}",
        "  function draw(){ if(!images[i]) return; ctx.drawImage(images[i],0,0); }",
        "  function tick(){ draw(); i=(i+1)%count; }",
        "  function start(){ if(timer) clearInterval(timer); i=0; timer=setInterval(tick,50); tick(); }",
        "  var pending=count;",
        "  for(var f=0;f<count;f++){",
        "    (function(idx){",
        "      var img=new Image();",
        "      img.onload=function(){ images[idx]=img; pending--; if(pending===0) start(); };",
        "      img.src=base+'/'+pad(idx)+'.png';",
        "    })(f);",
        "  }",
        "  var btn=box.querySelector('[data-act=restart]');",
        "  if(btn) btn.addEventListener('click', start);",
        "});",
        "</script>",
        "</body></html>"
    ) -join "`n"

    $report = Join-Path $ArtifactsRoot "index.html"
    Set-Content -Path $report -Value $html -Encoding utf8
    return $report
}

New-Item -ItemType Directory -Force -Path $ArtifactsRoot | Out-Null
$wanted = $Scenarios.Split(",") | ForEach-Object { $_.Trim().ToLower() } | Where-Object { $_ }
$results = @()
$failed = 0

foreach ($name in $wanted) {
    if (-not $ScenarioMap.Contains($name)) {
        Write-Warning "Unknown scenario '$name' - skip"
        continue
    }
    $meta = $ScenarioMap[$name]
    Write-Host ""
    Write-Host "=== e2e: $name (id=$($meta.Id)) - $($meta.Title) ===" -ForegroundColor Cyan

    Write-ScenarioHeader $meta.Id
    Get-ChildItem (Join-Path $Root "Debug") -Recurse -Filter "E2E*" -ErrorAction SilentlyContinue | Remove-Item -Force -ErrorAction SilentlyContinue
    $rebuild = @(
        "StateMenu.o", "StateGame.o", "StateBossRun.o", "StateBossFight.o",
        "StateGameOver.o", "StateWin.o", "E2E.o", "CameraDriver.o",
        "SpritePlayer.o", "BossRunPlayer.o", "BossFightPlayer.o"
    )
    Get-ChildItem (Join-Path $Root "Debug") -Recurse -Include $rebuild -ErrorAction SilentlyContinue | Remove-Item -Force -ErrorAction SilentlyContinue

    Build-E2ERom
    $outDir = Join-Path $ArtifactsRoot $name
    $run = Invoke-BgbRun $outDir $name

    $ok = [bool]$run.Ok
    $reason = [string]$run.Reason
    if ($ok) {
        $verdict = Get-RomVerdict $run.Shot
        if ($verdict -eq "fail") {
            $ok = $false
            $reason = "fail (ROM verdict FAIL: timeout, wrong room or unexpected GameOver/Win)"
        } elseif ($verdict -ne "pass") {
            $ok = $false
            $reason = "fail (no ROM verdict frame in final screenshot)"
        }
    }

    $row = [pscustomobject]@{
        Name       = $name
        Title      = $meta.Title
        Expect     = $meta.Expect
        Ok         = $ok
        Reason     = $reason
        Shot       = $run.Shot
        FrameCount = [int]$run.FrameCount
        Avis       = @($run.Avis)
    }
    $results += $row
    if ($row.Ok) {
        Write-Host "PASS $name" -ForegroundColor Green
    } else {
        Write-Host "FAIL $name - $($row.Reason)" -ForegroundColor Red
        $failed++
    }
}

Write-ScenarioHeader 0

$report = Write-ReportHtml $results
Write-Host ""
Write-Host "Report: $report"
if ($failed -gt 0) {
    Write-Host "$failed scenario(s) failed" -ForegroundColor Red
    exit 1
}
Write-Host "All scenarios passed" -ForegroundColor Green
exit 0
