#!/bin/bash
# Fast headless e2e (Linux): build one scenario ROM, run it in Peanut-GB.
#   tools/e2e/linux/e2e.sh <scenario> [max_game_seconds] [png_every_n_frames]
# Scenarios: die room1_die full_clear electric coins
# Output: tools/e2e/artifacts/linux/<scenario>/{result.txt,telemetry.csv,frames/,final.pgm}
# Env: GBDK (default ~/gbdk), EXTRA_SYMS="_sym _sym2:2" to log more RAM symbols.
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
RG=$(cd "$HERE/../../.." && pwd)
GBDK=${GBDK:-$HOME/gbdk}
declare -A IDS=([die]=1 [room1_die]=2 [full_clear]=3 [electric]=4 [coins]=5)
NAME=$1; ID=${IDS[$NAME]:-$NAME}; SECS=${2:-900}; SHOT=${3:-60}
[ -x "$HERE/rgrun" ] || gcc -O2 -o "$HERE/rgrun" "$HERE/rgrun.c"
cat > "$RG/include/E2E_scenario.h" <<H
/* Auto-generated by tools/e2e/run_e2e.ps1 - do not edit by hand while e2e is running. */
#ifndef E2E_SCENARIO
#define E2E_SCENARIO $ID
#endif
#define E2E_SEED ${SEED:-0}
H
restore() { cat > "$RG/include/E2E_scenario.h" <<H
/* Auto-generated by tools/e2e/run_e2e.ps1 - do not edit by hand while e2e is running. */
#ifndef E2E_SCENARIO
#define E2E_SCENARIO 0
#endif
H
}
trap restore EXIT
cd "$RG" && rm -f Debug/E2E.* Debug/E2EPlan.* Debug/E2EBoss.* Debug/State*.* Debug/SpritePlayer.* Debug/BossRunPlayer.* Debug/BossFightPlayer.* Debug/CameraDriver.* Debug/Rooms.*
rm -f "$RG/bin/READY_GAMER_Debug.gb"  # never run a stale ROM if the build fails
cd "$RG/src" && make build_gb BUILD_TYPE=Debug ZGB_PATH="$RG/ZGB_linux/ZGB/common" PATH="$GBDK/bin:/usr/bin:/bin" SHELL=/bin/bash ROMVIEW=true GBR2C="$HERE/bin/gbr2c" GBR2PNG="$HERE/bin/gbr2png" GBM2C="$HERE/bin/gbm2c" 2>&1 \
  | grep -E "error|Error|ERROR" || true
[ -f "$RG/bin/READY_GAMER_Debug.gb" ] || { echo "verdict=BUILD_FAILED"; exit 2; }
SYMS="_current_room _current_level _ready_coins:2 _player_lives _player_electric_attack _enemies_killed _enemies_to_spawn _enemies_left_to_spawn _e2e_keys _e2e_px:2 _e2e_py:2 _e2e_dbg _e2e_dbg2 $EXTRA_SYMS"
OUT="$RG/tools/e2e/artifacts/linux/$NAME"; rm -rf "$OUT"; mkdir -p "$OUT"
"$HERE/rgrun" "$RG/bin/READY_GAMER_Debug.gb" "$RG/Debug/rom.noi" "$OUT" $((SECS*60)) 30 $SHOT $SYMS || true
cat "$OUT/result.txt"
