/* Boss's sword-swing hitbox visual (BossSwordHitbox.c) — a 3-frame
 * rotating blade arc (diagonal -> diagonal -> straight, the middle
 * straight-ish interlude dropped to save VRAM tile budget — see below),
 * fixed position beside the boss (no sliding, no boss animation), always
 * pointed at the player.
 *
 * Only RIGHT and DOWN are stored here (6 frames, 24 tiles). LEFT is
 * RIGHT's frames drawn with the sprite's own H_MIRROR flag, UP is DOWN's
 * frames with V_MIRROR — BossSwordHitbox.c sets THIS->mirror instead of
 * this file storing 4 full copies of the tile data. This project's total
 * active sprite-tile budget in the boss fight (player + boss + both
 * bullet types + this + the player's own shot) landed at 164 tiles
 * against the hardware's 128-tile ceiling with the original 4-frame,
 * 4-direction version (64 tiles just for this file) — mirroring cut that
 * to 132, still over, so this also dropped one frame per direction
 * (32 -> 24 tiles) to land at 124, with a little headroom.
 *
 * Frame layout: 0-2 RIGHT, 3-5 DOWN.
 */

